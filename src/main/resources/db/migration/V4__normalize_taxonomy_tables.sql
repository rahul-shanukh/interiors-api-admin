
-- ============================================================
-- V4: Normalize taxonomy tables and add audit tracking
-- PostgreSQL / Neon
-- ============================================================

-- 1. Preserve the original V1 taxonomy table.
-- Existing foreign keys referencing it will follow the rename.
ALTER TABLE taxonomy_schema
    RENAME TO taxonomy_schema_legacy;


-- 2. Create the normalized taxonomy schema definition table.
CREATE TABLE taxonomy_schemas (
                                  type VARCHAR(100) PRIMARY KEY,
                                  description TEXT,
                                  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 3. Migrate existing taxonomy types into the new schema table.
INSERT INTO taxonomy_schemas (type)
SELECT type
FROM taxonomy_type
UNION
SELECT DISTINCT type
FROM taxonomy_schema_legacy;


-- 4. Create individual taxonomy schema values.
CREATE TABLE taxonomy_schema_value (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       schema_type VARCHAR(100) NOT NULL,
                                       value VARCHAR(128) NOT NULL,
                                       status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
                                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                       CONSTRAINT fk_taxonomy_schema_value_schema
                                           FOREIGN KEY (schema_type)
                                               REFERENCES taxonomy_schemas(type)
                                               ON DELETE RESTRICT,

                                       CONSTRAINT uk_taxonomy_schema_value_type_value
                                           UNIQUE (schema_type, value),

                                       CONSTRAINT chk_taxonomy_schema_value_status
                                           CHECK (status IN ('ACTIVE', 'DEPRECATED', 'ARCHIVED'))
);


-- 5. Migrate existing values into the normalized value table.
INSERT INTO taxonomy_schema_value (schema_type, value)
SELECT type, value
FROM taxonomy_schema_legacy;


-- 6. Create indexes for taxonomy values.
CREATE INDEX idx_taxonomy_schema_value_schema_type
    ON taxonomy_schema_value(schema_type);

CREATE INDEX idx_taxonomy_schema_value_status
    ON taxonomy_schema_value(status);


-- 7. Create taxonomy schema value audit table.
CREATE TABLE taxonomy_schema_value_audit (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             schema_value_id BIGINT NOT NULL,
                                             action VARCHAR(32) NOT NULL,
                                             previous_value VARCHAR(128),
                                             new_value VARCHAR(128),
                                             previous_status VARCHAR(32),
                                             new_status VARCHAR(32),
                                             reason TEXT,
                                             changed_by VARCHAR(128),
                                             metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
                                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                             CONSTRAINT fk_taxonomy_value_audit_value
                                                 FOREIGN KEY (schema_value_id)
                                                     REFERENCES taxonomy_schema_value(id)
                                                     ON DELETE RESTRICT,

                                             CONSTRAINT chk_taxonomy_value_audit_action
                                                 CHECK (
                                                     action IN (
                                                                'CREATED',
                                                                'UPDATED',
                                                                'DEPRECATED',
                                                                'REACTIVATED',
                                                                'ARCHIVED'
                                                         )
                                                     )
);


-- 8. Create audit indexes.
CREATE INDEX idx_taxonomy_value_audit_schema_value
    ON taxonomy_schema_value_audit(schema_value_id);

CREATE INDEX idx_taxonomy_value_audit_created_at
    ON taxonomy_schema_value_audit(created_at DESC);

CREATE INDEX idx_taxonomy_value_audit_value_created
    ON taxonomy_schema_value_audit(schema_value_id, created_at DESC);

